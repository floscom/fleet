func TestParseTranscriptClips(t *testing.T) {
	long := strings.Repeat("é", transcript.MaxText) // 2 bytes each
	cmd := strings.Repeat("ö", 150) + "\n" + strings.Repeat("x", transcript.MaxDetail)
	lines := []string{
		user(`"` + long + `"`),
		assistant(`[{"type":"text","text":"` + long + `"}]`),
		toolUseLine("Bash", `{"command":"`+strings.ReplaceAll(cmd, "\n", `\n`)+`"}`),
		user(`[{"tool_use_id":"t","type":"tool_result","content":"` + long + `"}]`),
		user(`"<local-command-stdout>` + long + `</local-command-stdout>"`),
	}
	a := New("", nil).(adapter.Transcripter)
	for i, l := range lines {
		es := a.ParseTranscript([]byte(l))
		if len(es) != 1 {
			t.Fatalf("line %d: %d entries", i, len(es))
		}
		checkEntry(t, es[0])
	}
}

// checkEntry checks the limits every entry must keep.
func checkEntry(t *testing.T, e transcript.Entry) {
	t.Helper()
	const slack = 32 // Clip's "… (n more bytes)"
	for _, f := range []struct {
		name, v string
		max     int
	}{{"Text", e.Text, transcript.MaxText}, {"Detail", e.Detail, transcript.MaxDetail}, {"Output", e.Output, transcript.MaxOutput}} {
		if !utf8.ValidString(f.v) {
			t.Errorf("%s %s is not UTF-8", e.Kind, f.name)
		}
		if len(f.v) > f.max+slack {
			t.Errorf("%s %s has %d bytes", e.Kind, f.name, len(f.v))
		}
	}
	if e.Kind == transcript.Tool && (strings.Contains(e.Text, "\n") || len(e.Text) > 200) {
		t.Errorf("tool summary %q is not one short line", e.Text)
	}
	switch e.Kind {
	case transcript.User, transcript.Assistant, transcript.Tool, transcript.Result, transcript.Note:
	default:
		t.Errorf("kind %q", e.Kind)
	}
}

func TestTranscriptDir(t *testing.T) {
	a := New("", nil).(adapter.Transcripter)
	t.Setenv("HOME", "/h")
	t.Setenv("CLAUDE_CONFIG_DIR", "")
	if got := a.TranscriptDir(""); got != "/h/.claude/projects" {
		t.Errorf("TranscriptDir = %q", got)
	}
	t.Setenv("CLAUDE_CONFIG_DIR", "/cfg")
	if got := a.TranscriptDir(""); got != "/cfg/projects" {
		t.Errorf("TranscriptDir with CLAUDE_CONFIG_DIR = %q", got)
	}
	if got := a.TranscriptDir("/sb"); got != "/sb/.claude/projects" {
		t.Errorf("TranscriptDir(/sb) = %q", got)
	}
}

func TestFindTranscript(t *testing.T) {
	const sid = "3f1c2a4e-7b5d-4e8a-9c1f-2d3e4f5a6b7c"
	dir := t.TempDir()
	write := func(rel string, age time.Duration) string {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte("{}\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		mt := time.Now().Add(-age)
		if err := os.Chtimes(p, mt, mt); err != nil {
			t.Fatal(err)
		}
		return p
	}
	write("-work-a/"+sid+".jsonl", time.Hour)
	newer := write("-work-b/"+sid+".jsonl", time.Minute)
	write("-work-c/"+sid+"/subagents/agent-a1.jsonl", 0)
	write("-work-c/other.jsonl", 0)
	if err := os.MkdirAll(filepath.Join(dir, "-work-d", sid+".jsonl"), 0o755); err != nil {
		t.Fatal(err)
	}

	a := New("", nil).(adapter.Transcripter)
	if got, ok := a.FindTranscript(dir, sid); !ok || got != newer {
		t.Errorf("FindTranscript = %q, %v, want %q", got, ok, newer)
	}
	for _, id := range []string{"", "agent-a1", "missing", "*", "3f1c*", "../-work-a/" + sid, "a/b", "a?b", "[3]f", ".", "..", sid + "\\x", strings.Repeat("a", 200)} {
		if got, ok := a.FindTranscript(dir, id); ok {
			t.Errorf("FindTranscript(%q) = %q", id, got)
		}
	}
}

// TestRealTranscripts parses every Claude Code transcript of the user
// running the test, to check the parser against real data after a Claude
// Code update. It prints nothing of their content.
func TestRealTranscripts(t *testing.T) {
	if os.Getenv("FLEET_REAL_TRANSCRIPTS") == "" {
		t.Skip("set FLEET_REAL_TRANSCRIPTS=1 to parse this machine's transcripts")
	}
	a := New("", nil).(adapter.Transcripter)
	files, _ := filepath.Glob(filepath.Join(a.TranscriptDir(""), "*", "*.jsonl"))
	kinds := map[string]int{}
	orphans := 0
	for _, f := range files {
		tools := map[string]bool{}
		for from := int64(0); ; {
			pg, err := transcript.Forward(f, from, a.ParseTranscript)
			if err != nil {
				t.Fatalf("%s: %v", f, err)
			}
			for _, e := range pg.Entries {
				checkEntry(t, e)
				kinds[e.Kind]++
				switch e.Kind {
				case transcript.Tool:
					tools[e.ID] = true
				case transcript.Result:
					if !tools[e.ID] {
						orphans++
					}
				}
			}
			if from = pg.End; !pg.More {
				break
			}
		}
	}
	t.Logf("%d files, entries %v, %d results without a tool call", len(files), kinds, orphans)
}
