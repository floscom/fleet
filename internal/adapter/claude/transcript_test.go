// Synthetic lines in the shape Claude Code 2.1.280 writes (fields the
// parser ignores mostly left out).
const (
	stamp = `"timestamp":"2026-09-27T10:00:00.250Z"`
	envl  = `"parentUuid":"p","isSidechain":false,"cwd":"/w","sessionId":"s","version":"2.1.280",` + stamp
)

var ms = time.Date(2026, 9, 27, 10, 0, 0, 250e6, time.UTC).UnixMilli()

func user(content string) string {
	return `{` + envl + `,"type":"user","message":{"role":"user","content":` + content + `},"uuid":"u"}`
}

func assistant(content string) string {
	return `{` + envl + `,"type":"assistant","message":{"id":"msg_1","model":"claude-opus-5-5","role":"assistant","content":` + content + `},"uuid":"u"}`
}

func system(fields string) string {
	return `{` + envl + `,"type":"system",` + fields + `,"uuid":"u"}`
}

func toolUseLine(name, input string) string {
	return assistant(`[{"type":"tool_use","id":"toolu_1","name":"` + name + `","input":` + input + `}]`)
}

type Es = []transcript.Entry

func noteAt(text string) Es { return Es{{Kind: transcript.Note, Text: text, TimeMs: ms}} }

